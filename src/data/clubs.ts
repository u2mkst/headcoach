type Row = [number, string, string, number, string]

function build(league: string, country: string, base: number, rows: Row[]): ClubData[] {
  return rows.map(([n, name, short, strength, color]) => {
    const id = `club_${String(base + n).padStart(3, '0')}`
    return { id, name, short, country, league, strength, color, crest: asset(`assets/crests/${id}.png`) }
  })
}

